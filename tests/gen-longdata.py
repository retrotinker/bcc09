#!/usr/bin/env python3
"""Write tests/src/longdata.h: expected results of 32-bit long arithmetic
for tests/src/longops.c, from a model of C on a machine with 16-bit int
and 32-bit long, independent of bcc09.

Behavior that C leaves undefined follows libc/bcc (see ldiv.s and
lshift.s): division by zero gives quotient -1 (all ones) for a
non-negative dividend and 1 for a negative one, and the dividend as the
remainder; LONG_MIN / -1 is LONG_MIN; shift counts of 32 or more
(unsigned) give 0, or all sign bits for >> of a signed value.

usage: gen-longdata.py > src/longdata.h
"""

VALS = [0, 1, -1, 2, 7, -7, 255, 65535, 65536, -65536, 100000, -100000,
        0x12345678, 0x7FFFFFFF, -0x80000000, 0x55555555]
COUNTS = [0, 1, 2, 7, 8, 15, 16, 17, 24, 31, 32, 33, -1]
CSHIFT = [1, 7, 8, 15, 16, 17, 24, 31]
IVALS = [0, 1, -1, 255, 32767, -32768, 0x5555]	# ints, for conversions


def s32(x):
    x &= 0xFFFFFFFF
    return x - 0x100000000 if x & 0x80000000 else x


def u32(x):
    return x & 0xFFFFFFFF


def s16(x):
    x &= 0xFFFF
    return x - 0x10000 if x & 0x8000 else x


def udivmod(a, b):
    a, b = u32(a), u32(b)
    if b == 0:
        return 0xFFFFFFFF, a
    return a // b, a % b


def sdivmod(a, b):
    a, b = s32(a), s32(b)
    q, r = udivmod(abs(a), abs(b))
    if (a < 0) != (b < 0):
        q = -q
    if a < 0:
        r = -r
    return s32(q), s32(r)


def shl(a, n):
    n &= 0xFFFF
    return 0 if n >= 32 else s32(a << n)


def shr(a, n):
    a, n = s32(a), n & 0xFFFF
    return (-1 if a < 0 else 0) if n >= 32 else a >> n


def shru(a, n):
    n &= 0xFFFF
    return 0 if n >= 32 else u32(a) >> n


def cmpbits(a, b):
    sa, sb, ua, ub = s32(a), s32(b), u32(a), u32(b)
    bits = [sa < sb, sa <= sb, sa > sb, sa >= sb, sa == sb, sa != sb,
            ua < ub, ua <= ub, ua > ub, ua >= ub]
    return sum(1 << i for i, b in enumerate(bits) if b)


def table(ctype, name, values, fmt):
    out = ["%s %s[] = {" % (ctype, name)]
    line = "\t"
    for v in values:
        item = fmt(v) + ", "
        if len(line) + len(item) > 72:
            out.append(line.rstrip())
            line = "\t"
        line += item
    out.append(line.rstrip())
    out.append("};")
    return "\n".join(out)


def ltab(name, values):
    # hex, so that the constants don't depend on how the compiler
    # handles the most negative long
    return table("long", name, values, lambda v: "0x%08lxL" % u32(v))


def itab(name, values):
    return table("int", name, values, lambda v: "%d" % s16(v))


def main():
    pairs = [(a, b) for a in VALS for b in VALS]
    shifts = [(a, n) for a in VALS for n in COUNTS]
    print("/* generated by tests/gen-longdata.py: don't edit */")
    print()
    print("#define NV %d" % len(VALS))
    print("#define NC %d" % len(COUNTS))
    print("#define NI %d" % len(IVALS))
    print(ltab("vals", VALS))
    print(itab("counts", COUNTS))
    print(itab("ivals", IVALS))
    print()
    print("/* for each a in vals, for each b in vals */")
    print(ltab("ladd", [a + b for a, b in pairs]))
    print(ltab("lsub", [a - b for a, b in pairs]))
    print(ltab("land", [a & b for a, b in pairs]))
    print(ltab("lor", [a | b for a, b in pairs]))
    print(ltab("leor", [a ^ b for a, b in pairs]))
    print(ltab("lmul", [a * b for a, b in pairs]))
    print(ltab("sdiv", [sdivmod(a, b)[0] for a, b in pairs]))
    print(ltab("smod", [sdivmod(a, b)[1] for a, b in pairs]))
    print(ltab("udiv", [udivmod(a, b)[0] for a, b in pairs]))
    print(ltab("umod", [udivmod(a, b)[1] for a, b in pairs]))
    print("/* bits: signed <, <=, >, >=, ==, !=, then unsigned <, <=, >, >= */")
    print(itab("cmp", [cmpbits(a, b) for a, b in pairs]))
    print()
    print("/* for each a in vals, for each n in counts */")
    print(ltab("sshl", [shl(a, n) for a, n in shifts]))
    print(ltab("sshr", [shr(a, n) for a, n in shifts]))
    print(ltab("ushr", [shru(a, n) for a, n in shifts]))
    print()
    print("/* for each a in vals: a << c, a >> c, (unsigned long)a >> c for")
    print("   constants c in CSHIFT */")
    rows = []
    for a in VALS:
        for c in CSHIFT:
            rows += [shl(a, c), shr(a, c), shru(a, c)]
    print(ltab("cshift", rows))
    print()
    print("/* for each a in vals: -a, ~a, a + 1 (++), a - 1 (--) */")
    rows = []
    for a in VALS:
        rows += [-a, ~a, a + 1, a - 1]
    print(ltab("unary", rows))
    print("/* for each a in vals: !a, then (int)a */")
    rows = []
    for a in VALS:
        rows += [int(s32(a) == 0), s16(a)]
    print(itab("tests", rows))
    print("/* for each i in ivals: (long)i, (long)(unsigned)i */")
    rows = []
    for i in IVALS:
        rows += [s16(i), i & 0xFFFF]
    print(ltab("widen", rows))


main()
