#!/usr/bin/env python3
"""Write tests/src/opsdata.h: expected results of 16-bit arithmetic for
tests/src/ops.c, from a model of C on a 16-bit machine (int and unsigned
are 16 bits), independent of bcc09.

Behavior that C leaves undefined follows libc/bcc: division by zero
gives quotient -1 (that is $FFFF) for a non-negative dividend and 1 for a
negative one, and the dividend as the remainder; -32768 / -1 is -32768;
shift counts of 16 or more (unsigned) give 0, or all sign bits for >> of
a signed value.

usage: gen-opsdata.py > src/opsdata.h
"""

VALS = [0, 1, -1, 2, 7, -7, 255, 256, 1000, -1000, 12345, 32767, -32768,
        0x5555]
COUNTS = list(range(18)) + [-1]
# constant operands that cc1 compiles inline instead of calling helpers
CDIV = [1, 2, 4, 8, 256, 3, 10]
CMUL = [0, 1, 2, 3, 4, 10, 256, 257]
CSHIFT = [0, 1, 3, 8, 15]


def s16(x):
    x &= 0xFFFF
    return x - 0x10000 if x & 0x8000 else x


def u16(x):
    return x & 0xFFFF


def udivmod(a, b):
    a, b = u16(a), u16(b)
    if b == 0:
        return 0xFFFF, a
    return a // b, a % b


def sdivmod(a, b):
    a, b = s16(a), s16(b)
    q, r = udivmod(abs(a), abs(b))
    if (a < 0) != (b < 0):
        q = -q
    if a < 0:
        r = -r
    return s16(q), s16(r)


def shl(a, n):
    n = u16(n)
    return 0 if n >= 16 else s16(a << n)


def shr(a, n):
    a, n = s16(a), u16(n)
    return (-1 if a < 0 else 0) if n >= 16 else a >> n


def shru(a, n):
    n = u16(n)
    return 0 if n >= 16 else u16(a) >> n


def table(name, values):
    out = ["int %s[] = {" % name]
    line = "\t"
    for v in values:
        item = "%d, " % s16(v)
        if len(line) + len(item) > 72:
            out.append(line.rstrip())
            line = "\t"
        line += item
    out.append(line.rstrip())
    out.append("};")
    return "\n".join(out)


def main():
    pairs = [(a, b) for a in VALS for b in VALS]
    shifts = [(a, n) for a in VALS for n in COUNTS]
    print("/* generated by tests/gen-opsdata.py: don't edit */")
    print()
    print("#define NV %d" % len(VALS))
    print("#define NC %d" % len(COUNTS))
    print(table("vals", VALS))
    print(table("counts", COUNTS))
    print()
    print("/* for each a in vals, for each b in vals */")
    print(table("smul", [a * b for a, b in pairs]))
    print(table("sdiv", [sdivmod(a, b)[0] for a, b in pairs]))
    print(table("smod", [sdivmod(a, b)[1] for a, b in pairs]))
    print(table("udiv", [udivmod(a, b)[0] for a, b in pairs]))
    print(table("umod", [udivmod(a, b)[1] for a, b in pairs]))
    print()
    print("/* for each a in vals, for each n in counts */")
    print(table("sshl", [shl(a, n) for a, n in shifts]))
    print(table("sshr", [shr(a, n) for a, n in shifts]))
    print(table("ushr", [shru(a, n) for a, n in shifts]))
    print()
    print("/* for each a in vals: a / c, a % c, a * c and a << c, a >> c "
          "with constants")
    print("   (signed, then unsigned) */")
    rows = []
    for a in VALS:
        for c in CDIV:
            rows += [sdivmod(a, c)[0], sdivmod(a, c)[1],
                     udivmod(a, c)[0], udivmod(a, c)[1]]
    print(table("cdivmod", rows))
    print(table("cmul", [a * c for a in VALS for c in CMUL]))
    rows = []
    for a in VALS:
        for c in CSHIFT:
            rows += [shl(a, c), shr(a, c), shru(a, c)]
    print(table("cshift", rows))


main()
